    private PassCheckOne checker = new PassCheckOne();
    private PassGameOne game = new PassGameOne();
    
    public void checkPassword() {
        String input = passwordField.getText();
        
        if(checker.hasConflict(input)) {
            outputArea.setText("There is a conflict in your password");
            return;
        }
        
        jProgressBar1.setValue(game.countPassed(input));
        jProgressBar1.setMaximum(game.totalRules());
        outputArea.setText(game.showMessage(input));
        
    }
